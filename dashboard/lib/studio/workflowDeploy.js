/**
 * Live execution of activated workflows (Platform Phase 3, completed).
 *
 * Studio has no hosting of its own, so ACTIVE workflows run inside the
 * owner's own bot on their paired self-hosted runner: at deploy time the
 * server (after re-checking Premium) adds each active, valid workflow as
 * plain discord.js code (workflows.exportCode: no eval, fixed strings) plus
 * one loader in src/events that registers them when the bot is ready.
 * The generated bot already loads every file in src/events, so the owner's
 * own code is never modified. discord.js (JavaScript) projects only.
 */
const wf = require('./workflows');

const LOADER_PATH = 'src/events/zigbotStudioWorkflows.js';

// Gateway intents each trigger needs (the template decides which the bot has).
const TRIGGER_INTENTS = {
    'trigger.member_join': ['GuildMembers'], 'trigger.member_leave': ['GuildMembers'],
    'trigger.message_create': ['GuildMessages', 'MessageContent'], 'trigger.message_update': ['GuildMessages', 'MessageContent'], 'trigger.message_delete': ['GuildMessages'],
    'trigger.reaction_add': ['GuildMessageReactions'], 'trigger.voice_state': ['GuildVoiceStates']
};

const LOADER = `// Generated by ZiGBoT Studio: runs your ACTIVE Studio workflows (Premium).
// Re-created on every deploy; edit workflows in Studio, not here.
const fs = require('node:fs');
const path = require('node:path');
const { Events } = require('discord.js');

module.exports = {
    name: Events.ClientReady,
    once: true,
    execute(client) {
        const dir = path.join(__dirname, '..', 'workflows');
        if (!fs.existsSync(dir)) return;
        for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.js'))) {
            try {
                require(path.join(dir, file))(client);
                console.log('[zigbot studio] workflow active:', file);
            } catch (error) {
                console.error('[zigbot studio] workflow failed to start:', file, error?.message || error);
            }
        }
    }
};
`;

/**
 * Files to add to a deploy bundle for these stored workflows.
 * Returns { files, included: [{ id, name }], skipped: [{ name, reason }], intents: [..] }.
 */
function buildWorkflowFiles(workflows, { framework }) {
    const out = { files: [], included: [], skipped: [], intents: [] };
    const active = (workflows || []).filter((w) => w.active);
    if (!active.length) return out;
    if (framework !== 'discordjs') {
        for (const w of active) out.skipped.push({ name: w.name, reason: 'Live workflows run in discord.js (JavaScript) projects only.' });
        return out;
    }
    const used = new Set();
    const intents = new Set();
    for (const w of active) {
        const code = wf.exportCode(w.graph, { name: w.name });
        if (code.error) { out.skipped.push({ name: w.name, reason: 'It no longer validates; fix it in the builder.' }); continue; }
        let p = code.path; let n = 2;
        while (used.has(p)) p = code.path.replace(/\.js$/, `_${n++}.js`);
        used.add(p);
        out.files.push({ path: p, content: code.content });
        out.included.push({ id: w.id, name: w.name });
        for (const node of w.graph?.nodes || []) for (const i of TRIGGER_INTENTS[node.type] || []) intents.add(i);
    }
    if (out.files.length) out.files.push({ path: LOADER_PATH, content: LOADER });
    out.intents = [...intents].sort();
    return out;
}

module.exports = { buildWorkflowFiles, LOADER_PATH, TRIGGER_INTENTS };
